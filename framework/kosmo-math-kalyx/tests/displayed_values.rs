//! Values: the answers of kalyx 0.1.0's answer vectors that fit one
//! insertion, computed by kalyx 0.1.0 under its default limits and the
//! versions 0. Each request gives the expected value line, whose display
//! text is the answer by its terms, and the display item read from it
//! renders as expected. For a fixed set of seeds, building the items in a
//! random order, each from its line or with the model's constructor, and
//! rendering each twice gives the same text.

mod support;

use kalyx::command::serialize;
use kalyx::{Limits, Request, execute};
use kosmo_math_kalyx::read_output_line;
use kosmo_math_model::EditBuffer;
use kosmo_math_model::display::{Content, DisplayItem, Freshness};
use kosmo_math_model::version::Versions;
use support::{Checked, TOO_LONG, answers, context, equal_terms, wide};

/// The seed of the first order; order `n` uses `SEED + n`.
const SEED: u64 = 0x6b6f_736d_6f00_0200;

/// The number of orders in which the items are built.
const ORDERS: u64 = 1_000;

/// The start of a value line of the versions 0.
const VALUE_LINE: &str = "value\t0\t0\t0\t";

/// The value line of one answer, without its line feed, the length of its
/// display text and its rendering as the current result.
struct Value {
    vector: &'static str,
    line: &'static str,
    text_bytes: usize,
    rendered: &'static str,
}

impl Value {
    /// The display text of the line.
    fn text(&self) -> Checked<&'static str> {
        Ok(self
            .line
            .strip_prefix(VALUE_LINE)
            .ok_or("a value line of the versions 0")?)
    }

    /// The line as kalyx writes it, with its line feed.
    fn written(&self) -> Vec<u8> {
        format!("{}\n", self.line).into_bytes()
    }
}

/// The SplitMix64 generator. When a test panics while a generator is alive,
/// it reports its seed and how many values it produced.
struct SplitMix64 {
    seed: u64,
    state: u64,
    drawn: u64,
}

impl SplitMix64 {
    fn new(seed: u64) -> SplitMix64 {
        SplitMix64 {
            seed,
            state: seed,
            drawn: 0,
        }
    }

    fn next(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9e37_79b9_7f4a_7c15);
        self.drawn += 1;
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    /// A value in `0..bound`, up to the generator's bias; `bound` is not 0.
    fn below(&mut self, bound: usize) -> usize {
        (self.next() % bound as u64) as usize
    }
}

impl Drop for SplitMix64 {
    fn drop(&mut self) {
        if std::thread::panicking() {
            eprintln!(
                "random order: seed {:#x}, failure after {} values were drawn",
                self.seed, self.drawn
            );
        }
    }
}

#[test]
fn the_value_line_of_each_answer_renders_as_expected() -> Checked {
    let answers = answers()?;
    let within: Vec<_> = answers
        .iter()
        .filter(|answer| !TOO_LONG.contains(&answer.id))
        .collect();
    assert_eq!(within.len(), VALUES.len());
    // A value has no place in the line, so the empty line, whose source
    // version is 0 like that of the requests, stands for the snapshot.
    let empty = EditBuffer::new().snapshot();
    for (answer, value) in within.iter().zip(&VALUES) {
        let id = answer.id;
        assert_eq!(id, value.vector);
        let request = Request::new(answer.operation, answer.variable, answer.input);
        let mut context = context(Limits::new());
        let outcome = execute(&request, &mut context);
        let written = serialize(&outcome, &mut context)?;
        assert_eq!(written, value.written(), "{id}");
        let text = value.text()?;
        assert_eq!(text.len(), value.text_bytes, "{id}");
        assert!(
            equal_terms(text, answer.answer, wide())?,
            "{id}: the terms differ"
        );
        let item = read_output_line(&written, Versions::default(), &empty);
        let built = DisplayItem {
            versions: Versions::default(),
            content: Content::Value(text.to_string()),
        };
        assert_eq!(item, built, "{id}");
        assert_eq!(item.render(Freshness::Current), value.rendered, "{id}");
    }
    Ok(())
}

#[test]
fn any_order_of_building_gives_the_same_renderings() -> Checked {
    let empty = EditBuffer::new().snapshot();
    let mut from_lines = 0;
    for n in 0..ORDERS {
        let mut rng = SplitMix64::new(SEED.wrapping_add(n));
        let mut order: Vec<usize> = (0..VALUES.len()).collect();
        for i in (1..order.len()).rev() {
            order.swap(i, rng.below(i + 1));
        }
        let mut items = Vec::with_capacity(order.len());
        for &index in &order {
            let value = &VALUES[index];
            let item = if rng.below(2) == 0 {
                from_lines += 1;
                read_output_line(&value.written(), Versions::default(), &empty)
            } else {
                DisplayItem {
                    versions: Versions::default(),
                    content: Content::Value(value.text()?.to_string()),
                }
            };
            items.push((value, item));
        }
        for (value, item) in &items {
            let first = item.render(Freshness::Current);
            let second = item.render(Freshness::Current);
            assert_eq!(first, second, "{}", value.vector);
            assert_eq!(first, value.rendered, "{}", value.vector);
        }
    }
    // Both ways of building took part.
    let built = ORDERS * VALUES.len() as u64;
    assert!(0 < from_lines && from_lines < built);
    Ok(())
}

